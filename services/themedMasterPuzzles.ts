// Helper to look up a thematic puzzle by theme ID, strictly respecting requested gridSize and minimizing overlap with usedWords
export function findThematicMasterPuzzle(
    themeId: string, 
    usedWords: Set<string> = new Set(), 
    attemptNumber: number = 1,
    gridSize?: number
): MasterGridPuzzle | undefined {
    if (!themeId || themeId === 'auto') return undefined;

    let matching = THEMATIC_MASTER_PUZZLES.filter(p => p.id.startsWith(themeId) || p.theme.includes(themeId));
    if (gridSize) {
        matching = matching.filter(p => p.gridSize === gridSize);
    }
    if (matching.length === 0) return undefined;
    if (matching.length === 1) return matching[0];

    // Find candidate with lowest word overlap to guarantee 100% fresh words
    const startIndex = (Math.max(1, attemptNumber) - 1) % matching.length;
    let bestCandidate = matching[startIndex];
    let minOverlap = Infinity;

    for (let i = 0; i < matching.length; i++) {
        const candidate = matching[(startIndex + i) % matching.length];
        const overlap = candidate.clues.filter(c => usedWords.has(c.word)).length;
        if (overlap < minOverlap) {
            minOverlap = overlap;
            bestCandidate = candidate;
            if (overlap === 0) break;
        }
    }
    return bestCandidate;
}
